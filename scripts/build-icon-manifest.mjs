import { access, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const complete = "Fractal-Symbols-Complete-Pack";
const legacy = "FractalSymbols Icons Set";
const legacyOnly = {
  Board: ["Agent circle","Agent rect","Agent square","Disc circle","Disc rect","Disc square","Empty rect","Hex grid filled","Hex grid line","Hollow banner","Meeple circle","Meeple rect","Meeple square","Pawn circle","Pawn rect","Pawn square","Simple banner","Track components","Track end","Track middle","Track single line"],
  Box: ["Complexity rating","Luck rating","Strategy rating"],
  Combat: ["Skull"],
  Element: ["Air hex","Arcane hex","Death hex","Earth hex","Fire hex","Life hex","Water hex"],
  Piece: ["DiscCube","DiscCube add","DiscCube minus","DiscCube move","DiscCube place","DiscCube remove","DiscCube return"],
  Resource: ["Clay","Coal"],
};
const display = (file) => file.replace(/\.svg$/i, "").replace(/[-_]+/g, " ").replace(/([a-z])([A-Z])/g, "$1 $2").replace(/([A-Za-z])(\d)/g, "$1 $2").replace(/\s+/g, " ").trim().replace(/^./, (v) => v.toUpperCase());
const icons = [];
async function add(category, filename, folder) {
  const name = display(filename);
  const png = filename.replace(/\.svg$/i, ".png");
  const pngPath = `${folder}/${category}/PNG/${png}`;
  icons.push({
    id: `${category}-${name}`.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""),
    name, category, path: `${folder}/${category}/SVG/${filename}`,
    thumbnail: await access(path.join(root, pngPath)).then(() => pngPath).catch(() => `${folder}/${category}/SVG/${filename}`),
    attribution: "fractal-symbols",
  });
}
for (const category of (await readdir(path.join(root, complete), { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name).sort()) {
  const dir = path.join(root, complete, category, "SVG");
  let files = [];
  try { files = await readdir(dir); } catch {}
  for (const file of files.filter((f) => f.toLowerCase().endsWith(".svg")).sort()) await add(category, file, complete);
}
for (const [category, names] of Object.entries(legacyOnly)) {
  for (const name of names) await add(category, `${name}.svg`, legacy);
}
icons.sort((a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name));
await writeFile(path.join(root, "icon-manifest.js"), `// Generated by scripts/build-icon-manifest.mjs\nwindow.PROTOTYPER_ICONS = ${JSON.stringify(icons, null, 2)};\n`);
console.log(`Wrote ${icons.length} icons.`);
